さらに、契約を譲渡する際には、契約相手への対価が必要となる。
契約相手が譲渡を拒否した場合、契約者側だけの判断で契約を譲渡することはできない。
譲渡後に契約内容を変更する場合は、通常の契約内容の変更と同様に、改めて双方の合意が必要となる。


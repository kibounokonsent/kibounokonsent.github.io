【概要】
異なる存在同士が、双方の合意によって結ぶ特殊な契約。
契約者と契約相手の間に特別な繋がりを生み、契約内容に応じて様々な効果が発生する。
契約相手に特定の種族による制限はなく、契約を成立させることのできる存在であれば契約相手となることができる。
契約の内容や条件には非常に大きな自由度があり、契約ごとに性質が異なる。

【契約者】
契約を結ぶ側の存在。
人間に限らず、契約を結べる存在であれば契約者になることができる。
契約によって能力や権利などを得る場合があるが、必ず何かを得られるとは限らない。

【契約相手】
契約者と契約を結ぶ側の存在。
契約を成立させることのできる存在が契約相手となる。
契約相手によって、契約の性質や条件は大きく異なる。

【契約の成立】
契約者と契約相手、双方の合意によって成立する。
契約内容には、
・何を与えるか
・何を受け取るか
・何を対価とするか
・どのような効果を発生させるか
・どのような条件を設けるか
などを設定できる。
そのため、契約ごとに内容は大きく異なる。

【対価】
契約によっては、何らかの対価が必要になる。
ただし、対価が必須というわけではない。
双方が合意していれば、対価なしの契約も成立する。
対価の内容にも決まった形式はなく、契約によって異なる。

【対価の支払い時期】
対価をいつ支払うのかは、契約内容によって異なる。
契約成立時に支払う場合もあれば、契約によって定められた条件を満たした時点や、契約期間中に継続して支払う場合などもある。
対価の支払い時期に共通したルールは存在しない。

【契約によって得られるもの】
契約によって得られるものも一定ではない。
例えば、
・能力の使用
・契約相手の召喚
・特定の権利
・特定の条件下での恩恵
・契約相手からの協力
など。
一方で、契約しても契約相手の能力を使用できない場合もある。

【契約期間】
契約の有効期間は、契約内容によって異なる。
契約期間については契約相手側が条件として提示することが多いが、最終的には契約者との合意によって決定される。
そのため、
・一定期間のみ有効
・特定の条件を満たすまで継続
・契約者が生存している間のみ継続
・期限を設定しない
など、様々な形が存在する。

【契約の終了】
契約がどのような条件で終了するのかは、契約内容によって異なる。
契約者または契約相手が死亡した場合でも、必ずしも契約が終了するとは限らない。
契約内容によっては、
・契約条件の達成
・契約期間の終了
・双方の合意
・特定の条件を満たす
・契約者または契約相手の死亡
などによって契約が終了する。
一方で、どのような状況でも解除されない契約も存在する。
そのような契約では、契約者が死亡した場合でも契約そのものは消滅せず、場合によっては転生後の契約者へ引き継がれることもある。

【契約内容の変更】
成立した契約でも、契約者と契約相手の双方が合意すれば変更可能。
ただし、契約内容の変更によって新たな利益や能力などを得る場合は、それに応じた追加の対価が必要になる場合がある。
変更後の条件についても、双方の合意が必要。

【契約違反】
契約に違反した場合の扱いは、契約内容によって異なる。
違反した場合の罰則を設定することもできるが、必ずしも罰則を設定する必要はない。
例えば、
・契約が解除される
・違反した側に罰則が発生する
・追加の対価が発生する
・契約上の権利を失う
・特に罰則を設定しない
など。
契約に定められていない罰則が、契約違反によって自動的に発生するわけではない。

【複数の契約】
一人の存在が複数の契約相手と契約することは可能。
ただし、複数の契約を結べるかどうかは契約内容によって異なる場合がある。
また、既に契約している契約相手が、新たな契約を結ぶことを拒否する場合もある。
その場合、既存の契約があることによって新たな契約を自由に結べるとは限らない。

【契約の可視化】
契約が外見や身体などに現れるかどうかは、契約相手が決める。
契約の証として何らかの痕跡を残すこともあれば、契約したことが外見上まったく分からない場合もある。
ただし、契約の可視化そのものを重要視しない契約相手も多く、特に何も変化させない場合が多い。
例えば、
・契約痕を残す
・契約印を刻む
・身体の一部に変化を起こす
・契約相手と同じ特徴を与える
・特に何も変化させない
など。

【契約の譲渡】
成立した契約を、別の存在へ譲渡することができる。
ただし、譲渡には、
・元の契約者
・契約相手
・譲渡先となる存在
